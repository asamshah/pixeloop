import { getTenantId } from "@/lib/tenant";
import { listConnections } from "@/lib/connections";
import { ConnectForm, type Field } from "@/components/connect-form";
import { CONNECTION_LABEL, type ConnectionKind } from "@/lib/platforms/types";

