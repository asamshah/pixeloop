export default async function ConnectPage() {
  const connections = await listConnections(await getTenantId());

  return (
    <main className="mx-auto max-w-4xl space-y-8 px-4 py-8">
      <header>
        <h1 className="text-2xl font-semibold">Connections</h1>
        <p className="text-sm text-neutral-500">
          Credentials are validated against the platform, then stored encrypted (AES-256-GCM).
          They are never shown again or sent back to the browser.
        </p>
      </header>

      {(Object.keys(FIELDS) as ConnectionKind[]).map((platform) => {
        const conn = connections.find((c) => c.platform === platform);
        return (
          <section key={platform} className="space-y-4 rounded-lg border p-5">
            <h2 className="text-lg font-medium">{CONNECTION_LABEL[platform]}</h2>
            <ConnectForm
              platform={platform}
              fields={FIELDS[platform]}
              connectedAs={conn ? (conn.displayName ?? "connected") : null}
            />
          </section>
        );
      })}
    </main>
  );
}
